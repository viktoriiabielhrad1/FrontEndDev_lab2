        <div class="col3">
            <h3>WHY IS IT CALLED SQUID GAME?</h3>
            <p>
                The title refers to a traditional Korean children's game called "squid game" (ojingeo ggai) that is similar to tag. The game is played on a squid-shaped field and involves teams trying to push each other out of the designated area. The show uses this innocent childhood game as a dark metaphor for the brutal competition in the series.
            </p>
        </div>
        <div class="col3">
            <h3>WHO CREATED SQUID GAME?</h3>
            <p>
                Squid Game was created by Hwang Dong-hyuk, a South Korean filmmaker. He first conceived the idea in 2008 but struggled to find a production company willing to fund it. After nearly a decade of rejections, Netflix picked up the project in 2019. Hwang wrote and directed the entire first season.
            </p>
        </div>
        <div class="col3">
            <h3>HOW MANY EPISODES ARE THERE?</h3>
            <p>
                The first season consists of 9 episodes, ranging from 32 to 63 minutes each. The episodes are titled after the games players must complete: Red Light Green Light, Sugar Honeycombs, Tug of War, Marbles, SSangttopp, and the final Squid Game.
            </p>
        </div>
    </div>

    <div class="row">
        <div class="col3">
            <h3>WHAT ARE THE DEADLY GAMES?</h3>
            <p>
                Players must complete six childhood games: Red Light Green Light (where moving during the red light results in death), Sugar Honeycombs (cutting out a shape without breaking it), Tug of War, Marbles, and a maskedrawing game. Each game is deadly, with most players eliminated when they fail or break the rules.
            </p>
        </div>
        <div class="col3">
            <h3>WHO IS SEONG GI-HUN?</h3>
            <p>
                Seong Gi-hun (Player 456) is the main protagonist of the series, played by Lee Jung-jae. He is a struggling gambler and divorced father who enters the game to escape debt. Throughout the series, he evolves from a selfish man into a determined survivor who ultimately wins and discovers the disturbing truth behind the games.
            </p>
        </div>
        <div class="col3">
            <h3>WHO IS OH IL-NAM?</h3>
            <p>
                Oh Il-nam (Player 001) appears to be an elderly man who needs help during the games, but he is secretly the creator and mastermind behind Squid Game. He created the deadly tournament as a twisted social experiment for wealthy elites, wanting to experience the thrill of survival one last time before dying from a brain tumor.
            </p>
        </div>
    </div>

    <div class="row">
        <div class="col3">
            <h3>WHAT THEMES DOES THE SHOW EXPLORE?</h3>
            <p>
                Squid Game explores themes of class inequality, capitalism, desperation, and the corruption of childhood innocence. The show critiques how modern society forces desperate people to risk their lives for wealth that the elite take for granted.
            </p>
        </div>
        <div class="col3">
            <h3>IS SQUID GAME BASED ON A TRUE STORY?</h3>
            <p>
                Squid Game is not based on a true story, though creator Hwang Dong-hyuk has said he was inspired by his own financial struggles in early adulthood and the economic inequality he witnessed in South Korea. The concept of deadly survival games exists in many works of fiction, including Battle Royale and The Hunger Games.
            </p>
        </div>
        <div class="col3">
            <h3>WILL THERE BE A SEASON 2?</h3>
            <p>
                Netflix confirmed Squid Game will return for a second season. Hwang Dong-hyuk has stated the new season will explore the identity of the Front Man (the game's organizer) and continue Seong Gi-hun's story as he seeks revenge against the game's creators. The exact release date has not been announced.
            </p>
        </div>
    </div>

    <div class="row">
        <div class="col2">
            <h3>WHAT MAKES SQUID GAME SO POPULAR?</h3>
            <p>
                Squid Game gained worldwide popularity due to its unique blend of violent thriller elements with commentary on capitalism and class struggle. The accessible children's game motifs combined with extreme violence created a memorable contrast. Strong performances, particularly by Lee Jung-jae and O Yeong-su, plus excellent production design, helped make it Netflix's most-watched series ever.
            </p>
